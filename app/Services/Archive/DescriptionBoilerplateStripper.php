<?php

namespace App\Services\Archive;

/**
 * 配信の概要欄には、その動画固有の内容とは無関係な定型文（宣伝告知・自己紹介・SNSリンク・
 * ハッシュタグの羅列など）が毎回貼り付けられていることが多く、ゲームジャンル判定や参加者名の
 * 抽出でこれを誤って拾ってしまう（例: 自己紹介文の「普段はマダミスも配信しています」が
 * その動画の内容だと誤認される）。判定に使う前に、これらの定型文をできるだけ取り除く。
 */
class DescriptionBoilerplateStripper
{
    public static function strip(string $description): string
    {
        $text = $description;

        // 「◥◣ 告知タイトル ◢◤」のような装飾で囲まれた告知ブロックを除去。
        $text = preg_replace('/◥◣.*?◢◤/su', '', $text) ?? $text;

        // 「◇「〇〇」について」から始まる自己紹介段落を、次の空行まで除去。
        $text = preg_replace('/◇「[^」]*」について.*?(?=\n\s*\n|\z)/su', '', $text) ?? $text;

        // 見出し行の直後にURLを含む行（URLのみ、または「公式CH  https://...」のような
        // ラベル＋URLの行）が続く「リンク紹介」ペアを、見出し行ごと除去する。URL行だけを消すと、
        // 見出し文言に「アルジャン」等の固定の宣伝文言が残ってしまい、動画本編の内容と誤認して
        // しまうため（例:「🐝アルジャン」の次行に「公式CH  https://...」が続くケース）。
        $text = preg_replace('/^.*\S.*\n(?=[ \t]*\S*[ \t]*https?:\/\/)/mu', '', $text) ?? $text;

        // URLを含む行（SNS・グッズ・メンバーシップ・お手紙宛先等の定型リンク行）を除去。
        $text = preg_replace('/^.*https?:\/\/\S+.*$/mu', '', $text) ?? $text;

        // 区切り線（ダッシュ・波線・二重線が連続する行）を除去。
        $text = preg_replace('/^[\-―=＝━_]{5,}\s*$/mu', '', $text) ?? $text;

        // ハッシュタグだけで構成される行（末尾のタグ羅列）を除去。
        // 「＃」（全角）を使うチャンネルもあるため、半角#と全角＃の両方、区切りの全角スペースも含めて判定する。
        $text = preg_replace('/^(?:[\s　]*[#＃]\S+[\s　]*)+$/mu', '', $text) ?? $text;

        // 「《〇〇のマイリスト》」「〇〇リスト：」のような、ジャンル・企画別の固定リンク集の
        // 見出し行を除去。これは動画本編の内容ではなく、チャンネル共通のリンク集であることが多い
        // （例:「アルジャン日々の配信リスト：」－ その動画がアルジャンとは限らない）。
        $text = preg_replace('/^.*《[^》]*マイリスト[^》]*》.*$/mu', '', $text) ?? $text;
        $text = preg_replace('/^.*リスト[：:]\s*$/mu', '', $text) ?? $text;

        // ライブ・フェス・物販等、別イベントの告知ブロックや、「■〇〇」のような普段の所属・肩書き
        // 紹介、グッズ販促（「📅」「🎫」「📍」「🗓」「📢」「チケット」「OPEN」「START」「出演」
        // 「会場」「開催決定」「フェス」「ワンマン」「ツアー」「グッズ」「■」等を含む段落）を
        // 段落ごと丸ごと除去する。行単位の除去だと、イベント名や肩書き自体の行（例:「アルジャン
        // ミュージックフェス ~ビビっとサマー！~」「■エンタメ人狼集団『アルジャン』」「アルジャン
        // ストアに新登場」）が残ってしまい、そこに「アルジャン」の文字列があるとこの動画自体の
        // 内容と誤認してタグ判定をすり抜けてしまうため、段落単位で除去する。
        $paragraphs = preg_split('/\n\s*\n+/', $text) ?: [$text];
        $paragraphs = array_filter(
            $paragraphs,
            fn (string $paragraph) => !preg_match(
                '/(?:📅|🎫|📍|🗓|📢|チケット|OPEN\s*\d|START\s*\d|出演者?[：:]|会場|開催決定|フェス|ワンマン|ツアー|グッズ|^■)/mu',
                $paragraph
            )
        );
        $text = implode("\n\n", $paragraphs);

        return trim(preg_replace('/\n{2,}/', "\n", $text) ?? $text);
    }
}
